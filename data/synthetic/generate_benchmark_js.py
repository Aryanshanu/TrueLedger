"""Generate frontend/public/data/benchmark_entities.generated.js from the
single canonical data/benchmark_entities.json.

Before this script existed, the 5 wizard benchmark personas (Annapurna,
Trisara, Virelion, Aravind, Nexvara) were hand-typed twice: once as
BENCHMARK_CASES in frontend/public/app.js, once as `entities` in
generate_sample_excels.py. The two copies had already drifted - PAN and
GSTIN differed for 4 of the 5 entities between the on-screen identity and
the identity baked into that entity's own downloadable GST return (its ARN
reference is derived from the PAN) - and the pre-rename "Kaveri Agro
Commodities Ltd" name survived in one copy after being fixed in the other.
Both scripts now read data/benchmark_entities.json as the single source.

This script keeps BENCHMARK_CASES a plain synchronous array (as every
existing call site in app.js expects) instead of switching it to a runtime
fetch - a fetch would make BENCHMARK_CASES empty until the network request
resolves, which the wizard's Step 2 benchmark cards and the case rail
currently assume is never true. Generating the same literal instead keeps
every existing call site correct by construction, with no behavioural
change, while still removing the hand-duplication that caused the bug.

Run with:  python -m data.synthetic.generate_benchmark_js
Output:    frontend/public/data/benchmark_entities.generated.js
"""

from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_JSON = REPO_ROOT / "data" / "benchmark_entities.json"
OUTPUT_JS = REPO_ROOT / "frontend" / "public" / "data" / "benchmark_entities.generated.js"

# INR values in the source JSON are plain integers (paise-free rupees);
# app.js's BENCHMARK_CASES has always displayed them pre-formatted in the
# Indian lakh/crore grouping (e.g. 85000000 -> "₹8,50,00,000"), so format
# them the same way here rather than pushing formatting logic into app.js.
def format_inr(value: int) -> str:
    s = str(int(value))
    if len(s) <= 3:
        return f"₹{s}"
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return f"₹{','.join(groups)},{tail}"


def build_benchmark_cases(entities: list[dict]) -> list[dict]:
    cases = []
    for e in entities:
        cases.append({
            "id": e["id"],
            "name": e["name"],
            "sector": e["sector"],
            "pan": e["pan"],
            "gstin": e["gstin"],
            "loan": format_inr(e["loan"]),
            "bank_inflows": format_inr(e["bank_inflows"]),
            "gst_turnover": format_inr(e["gst_turnover"]),
            "trend_bank": e["trend_bank"],
            "trend_gst": e["trend_gst"],
            "variance": e["variance"],
            "verdict": e["verdict"],
            "final_confidence": e["final_confidence"],
            "model_confidence": e["model_confidence"],
            "consent_multiplier": e["consent_multiplier"],
            "consent_days": e["consent_days"],
            "badge_class": e["badge_class"],
            "files": {
                "gstn": f"{e['id']}_gstr_returns.xlsx",
                "itr": f"{e['id']}_itr_filings.xlsx",
                "bank": f"{e['id']}_bank_statement.xlsx",
            },
            "narrative": e["narrative"],
        })
    return cases


def main() -> None:
    entities = json.loads(SOURCE_JSON.read_text(encoding="utf-8"))
    cases = build_benchmark_cases(entities)

    header = (
        "// AUTO-GENERATED by `python -m data.synthetic.generate_benchmark_js`.\n"
        "// Source of truth: data/benchmark_entities.json - edit that file and\n"
        "// regenerate, do not hand-edit this file (changes will be overwritten).\n"
    )
    body = "const BENCHMARK_CASES = " + json.dumps(cases, indent=2, ensure_ascii=False) + ";\n"

    OUTPUT_JS.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_JS.write_text(header + body, encoding="utf-8")
    print(f"Wrote {OUTPUT_JS} ({len(cases)} entities)")


if __name__ == "__main__":
    main()
